import "server-only";
import { FRAMEWORKS, TEMPLATE_CATEGORIES, TEMPLATES, type Template } from "@/templates";
import { TEMPLATE_SHOTS } from "@/components/templates/shots";
import { toolSchemas } from "@/lib/ai/tools/schemas";
import { tokenize, type Token } from "@/components/vignettes/tokenize";
import { DEFAULT_SCENARIO_ID, HOME_CHIPS } from "@/content/marketing/home";
import { TOKEN_KINDS, type CompactToken, type Scenario, type ScenarioWrite, type StageTools, type StarterLite } from "./types";

/**
 * Home-page scenarios, derived from the real starter templates at render time (PLAN §5.2):
 * real file paths, 16 consecutive lines of the real main file (tokenised here), the real
 * screenshot id, and plan steps that name real files. Nothing is generated by a model.
 *
 * Six starters are staged (the chip starters, PLAN §7.4 task 5), and only React + Vite
 * starters with a captured screenshot qualify: the replay's type-check → build → preview story
 * is true for them. Every other starter still takes part in the live match and the starter
 * picker; the stage then keeps its current scenario. The scenarios cross the RSC boundary,
 * so their payload is budgeted at 25 KB including the starter list.
 */

const CODE_LINES = 16;
const LINE_CHARS = 84;
const MAX_FILES = 12;
const MAX_SCENARIOS = 6;

/** Config and scaffolding that a plan would not talk about. */
const SCAFFOLD = new Set(["package.json", "vite.config.ts", "tsconfig.json", "index.html", "src/main.tsx", "src/index.css", "README.md", ".gitignore", "src/vite-env.d.ts", "src/useLocalStorage.ts"]);

const MAIN_CANDIDATES = ["src/App.tsx", "index.html", "src/server.ts"];

function categoryName(id: string) {
  return TEMPLATE_CATEGORIES.find((c) => c.id === id)?.name ?? id;
}

function frameworkName(t: Template) {
  return FRAMEWORKS[t.framework]?.name ?? t.framework;
}

function lineCount(src: string | undefined) {
  if (!src) return 0;
  return src.replace(/\n$/, "").split("\n").length;
}

function slugOf(name: string) {
  return name
    .replace(/\(.*?\)/g, "")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 24);
}

/** Sources first (data modules, then components), then scaffolding; at most MAX_FILES. */
function orderFiles(paths: string[]) {
  const rank = (p: string) => (p.startsWith("src/") && !SCAFFOLD.has(p) ? (p.endsWith(".tsx") ? 1 : 0) : SCAFFOLD.has(p) ? 3 : 2);
  return [...paths].sort((a, b) => rank(a) - rank(b) || a.localeCompare(b)).slice(0, MAX_FILES);
}

function basename(path: string) {
  const file = path.split("/").pop() ?? path;
  return file.replace(/\.[^.]+$/, "");
}

/** One plan step for a real file, phrased by what the file is. */
function stepFor(path: string): string {
  const base = basename(path);
  const lower = base.toLowerCase();
  if (/\/(screens|views|pages)\//.test(path)) return `Add the ${base} ${path.includes("/screens/") ? "screen" : "view"} in ${path}`;
  if (path.endsWith(".tsx")) return `Build the ${base} component in ${path}`;
  if (lower.includes("cart")) return `Keep the cart state in ${path}`;
  if (lower.includes("chat")) return `Send the conversation through ${path}`;
  if (lower === "api") return `Wrap data access in ${path}`;
  if (lower === "router") return `Set up routes in ${path}`;
  if (lower === "auth") return `Add the session helpers in ${path}`;
  return `Model the data in ${path}`;
}

function firstSentence(text: string) {
  const m = text.match(/^(.+?[.!?])(\s|$)/);
  return (m ? m[1] : text).trim();
}

/**
 * Where the stage's 16-line excerpt of the main file starts (0-based): at the component, where the
 * state and JSX live, rather than at the imports and the icon path data above it. The lines are
 * still the file's own, in order, and the editor numbers them with their real line numbers.
 */
function codeWindowStart(src: string): number {
  const lines = src.split("\n");
  let start = lines.findIndex((l) => /^export default function\b/.test(l));
  if (start < 0) start = lines.findIndex((l) => /^(export\s+)?function\s+App\b/.test(l));
  if (start < 0) return 0;
  // Keep a full window when the component starts near the end of the file.
  return Math.max(0, Math.min(start, lines.length - CODE_LINES));
}

/** Tokenise the CODE_LINES-line window from `start` and cap each line's width (it is clipped on screen anyway). */
function compactCode(src: string, path: string, start: number): CompactToken[][] {
  const head = src.split("\n").slice(start, start + CODE_LINES).join("\n");
  const lang = path.endsWith(".html") ? "html" : path.endsWith(".ts") ? "ts" : "tsx";
  const lines: Token[][] = tokenize(head, lang);
  return lines.map((line) => {
    const out: CompactToken[] = [];
    let width = 0;
    for (const t of line) {
      if (width >= LINE_CHARS) break;
      const v = t.v.slice(0, LINE_CHARS - width);
      width += v.length;
      const k = Math.max(0, TOKEN_KINDS.indexOf(t.k));
      const last = out[out.length - 1];
      if (last && last[0] === k) last[1] += v;
      else out.push([k, v]);
    }
    return out;
  });
}

/** The line (1-based, inside the excerpt) the illustrative type error points at: a state or const declaration, else a JSX attribute. */
function errorLineOf(src: string, start: number) {
  const lines = src.split("\n").slice(start, start + CODE_LINES);
  const pick = (re: RegExp) => lines.findIndex((l) => re.test(l));
  let i = pick(/useState\s*[<(]/);
  if (i < 0) i = pick(/^\s+const\s+\w+\s*=/);
  if (i < 0) i = pick(/\sclassName=/);
  if (i < 0) i = Math.min(lines.length - 1, 7);
  return i + 1;
}

function buildScenario(t: Template, prompt: string): Scenario | null {
  const paths = Object.keys(t.files);
  const mainFile = MAIN_CANDIDATES.find((p) => p in t.files);
  if (!mainFile) return null;
  const main = t.files[mainFile];
  const extras = orderFiles(paths).filter((p) => p !== mainFile && !SCAFFOLD.has(p));
  const writes: ScenarioWrite[] = extras.slice(0, 2).map((p) => ({ path: p, lines: lineCount(t.files[p]), action: "A" as const }));
  if (writes.length < 2 && "src/index.css" in t.files) writes.push({ path: "src/index.css", lines: lineCount(t.files["src/index.css"]), action: "M" });
  writes.push({ path: mainFile, lines: lineCount(main), action: "M" });

  const plan = [/starter$/i.test(t.name) ? `Start from the ${t.name} (${paths.length} files)` : `Start from the ${t.name} starter (${paths.length} files)`];
  for (const p of extras.slice(0, 2)) plan.push(stepFor(p));
  if (plan.length < 3) plan.push(`Lay out the screen in ${mainFile}`);
  if (plan.length < 3 && "src/index.css" in t.files) plan.push("Adjust the styles in src/index.css");
  plan.push(`Wire everything into ${mainFile}`);

  const fw = FRAMEWORKS[t.framework];
  const codeStart = codeWindowStart(main);
  return {
    id: t.id,
    name: t.name,
    slug: slugOf(t.name) || t.id,
    categoryName: categoryName(t.category),
    frameworkName: frameworkName(t),
    prompt,
    fileCount: paths.length,
    files: orderFiles(paths),
    mainFile,
    mainLines: lineCount(main),
    code: compactCode(main, mainFile, codeStart),
    codeStart: codeStart + 1,
    errorLine: errorLineOf(main, codeStart),
    writes,
    plan: plan.slice(0, 4),
    devCommand: fw?.devCommand ?? "npm run dev",
    port: fw?.port ?? 5173,
  };
}

/** Every starter as the matcher and the starter picker see it. Featured first, then registry order. */
export function buildStarters(staged: Set<string>): StarterLite[] {
  const list = TEMPLATES.map((t) => ({
    id: t.id,
    name: t.name,
    categoryName: categoryName(t.category),
    frameworkName: frameworkName(t),
    tags: t.tags,
    description: t.description,
    shot: TEMPLATE_SHOTS.has(t.id),
    staged: staged.has(t.id),
  }));
  // Featured starters lead the picker.
  return list.sort((a, b) => Number(Boolean(TEMPLATES.find((t) => t.id === b.id)?.featured)) - Number(Boolean(TEMPLATES.find((t) => t.id === a.id)?.featured)));
}

/**
 * Stage scenarios: the default starter, then the chip starters in chip order (at most six).
 */
export function buildScenarios(): Scenario[] {
  const byId = new Map(TEMPLATES.map((t) => [t.id, t]));
  const stageable = (t: Template | undefined): t is Template => Boolean(t && t.framework === "vite-react" && TEMPLATE_SHOTS.has(t.id) && "src/App.tsx" in t.files);
  const order: string[] = [];
  const push = (id: string) => {
    if (!order.includes(id) && stageable(byId.get(id))) order.push(id);
  };
  push(DEFAULT_SCENARIO_ID);
  HOME_CHIPS.forEach((c) => push(c.templateId));
  const prompts = new Map(HOME_CHIPS.map((c) => [c.templateId, c.prompt]));
  return order
    .map((id) => {
      const t = byId.get(id)!;
      return buildScenario(t, prompts.get(id) ?? firstSentence(t.description));
    })
    .filter((s): s is Scenario => s !== null)
    .slice(0, MAX_SCENARIOS);
}

/** Real tool names from the agent's registry; throws at render if the registry ever renames one. */
export function stageTools(): StageTools {
  const names = new Set(Object.keys(toolSchemas));
  const tools: StageTools = { list: "list_files", read: "read_file", plan: "propose_plan", write: "write_file", edit: "edit_file", run: "run_command", finish: "finish" };
  for (const n of Object.values(tools)) if (!names.has(n)) throw new Error(`Home stage uses an unknown agent tool: ${n}`);
  return tools;
}
