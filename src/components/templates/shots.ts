/**
 * Real screenshots of each template's own build, captured by `scripts/capture-template-shots.ts`
 * (1440×900 viewport; `<id>.webp` is 1440w, `<id>@2x.webp` 2880w when `retina`, `<id>-720.webp` when `small`).
 * The capture script rewrites the data block below; a template whose capture fails keeps its old shot
 * with `retina: false`, so `srcset` only ever references files that exist. Server- and client-safe.
 */
export type TemplateShot = {
  /** `<id>@2x.webp` (2880w) exists. */
  retina: boolean;
  /** `<id>-720.webp` (720w) exists. */
  small: boolean;
  /** `<id>-phone.webp` (390×844 viewport at 2×, 780w) exists — captured for mobile-first templates. */
  phone?: boolean;
};

// <capture-data> (generated by scripts/capture-template-shots.ts; edit by re-running the script)
const DATA: [string, TemplateShot][] = [
  ["static-blog", { retina: true, small: true }],
  ["static-landing", { retina: true, small: true }],
  ["static-portfolio", { retina: true, small: true }],
  ["static-site", { retina: true, small: true }],
  ["vite-react-admin", { retina: true, small: true }],
  ["vite-react-ai-chat", { retina: true, small: true }],
  ["vite-react-crm", { retina: true, small: true }],
  ["vite-react-dashboard", { retina: true, small: true }],
  ["vite-react-landing", { retina: true, small: true }],
  ["vite-react-mobile-shell", { retina: true, small: true, phone: true }],
  ["vite-react-ops-dashboard", { retina: true, small: true }],
  ["vite-react-portfolio", { retina: true, small: true }],
  ["vite-react-saas", { retina: true, small: true }],
  ["vite-react-starter", { retina: true, small: true }],
  ["vite-react-storefront", { retina: true, small: true }],
  ["vite-react-tasks", { retina: true, small: true }],
];
// </capture-data>

/** Templates with a real screenshot in /public/templates. `TEMPLATE_SHOTS.has(id)` is the stable check. */
export const TEMPLATE_SHOTS: ReadonlyMap<string, TemplateShot> = new Map(DATA);

/** Intrinsic size of `<id>.webp`. */
export const SHOT_WIDTH = 1440;
export const SHOT_HEIGHT = 900;

/** `src` of the 1440w screenshot. */
export function templateShotSrc(id: string) {
  return `/templates/${id}.webp`;
}

/** `srcset` listing only the files that exist for this template (undefined when there is no shot). */
export function templateShotSrcSet(id: string): string | undefined {
  const shot = TEMPLATE_SHOTS.get(id);
  if (!shot) return undefined;
  return [shot.small ? `/templates/${id}-720.webp 720w` : null, `/templates/${id}.webp ${SHOT_WIDTH}w`, shot.retina ? `/templates/${id}@2x.webp ${SHOT_WIDTH * 2}w` : null].filter(Boolean).join(", ");
}

/** `src` of the phone-viewport capture, when one exists. */
export function templatePhoneShotSrc(id: string): string | null {
  return TEMPLATE_SHOTS.get(id)?.phone ? `/templates/${id}-phone.webp` : null;
}

/** The smallest existing file at least `width` px wide (for fixed-size thumbnails without srcset). */
export function templateShotFor(id: string, width: number) {
  const shot = TEMPLATE_SHOTS.get(id);
  if (shot?.small && width <= 360) return `/templates/${id}-720.webp`;
  return templateShotSrc(id);
}
