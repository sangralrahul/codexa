/**
 * Deterministic scripted provider used ONLY when AI_MOCK=1 outside production.
 * It behaves like a small agent so the whole pipeline (tools, snapshots, runs,
 * SSE, UI) can be exercised without API keys. It is not a product feature and
 * the UI shows a "Mock AI (development only)" badge whenever it is active.
 */
import type { AiProvider, ChatMessage, ProviderEvent, ProviderRequest, ToolCall } from "../provider";

export function isMockEnabled(): boolean {
  return process.env.AI_MOCK === "1" && process.env.NODE_ENV !== "production";
}

function extractUserRequest(messages: ChatMessage[]): string {
  const first = messages.find((m) => m.role === "user");
  const text = first && first.role === "user" ? first.content : "";
  const m = text.match(/<user_request>([\s\S]*?)<\/user_request>/);
  return (m ? m[1] : text).trim().slice(0, 200) || "your request";
}

function priorToolCalls(messages: ChatMessage[]): ToolCall[] {
  const out: ToolCall[] = [];
  for (const m of messages) if (m.role === "assistant") out.push(...m.toolCalls);
  return out;
}

function toolOutput(messages: ChatMessage[], name: string): string | null {
  for (let i = messages.length - 1; i >= 0; i--) {
    const m = messages[i];
    if (m.role !== "tool") continue;
    const r = m.results.find((x) => x.name === name && !x.isError);
    if (r) return r.output;
  }
  return null;
}

function listedPaths(messages: ChatMessage[]): string[] {
  const out = toolOutput(messages, "list_files");
  if (!out) return [];
  return out
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith("…") && !l.startsWith("("))
    .map((l) => l.replace(/\s+\(\d+ B\)$/, ""));
}

function lastUserMessage(messages: ChatMessage[]): string {
  for (let i = messages.length - 1; i >= 0; i--) {
    const m = messages[i];
    if (m.role === "user") return m.content;
  }
  return "";
}

const featureComponent = (prompt: string) => `type FeatureProps = { title: string };

export function Feature({ title }: FeatureProps) {
  return (
    <section className="mt-6 rounded-xl border border-slate-200 bg-slate-50 p-4">
      <h2 className="text-sm font-semibold uppercase tracking-wide text-slate-500">Requested feature</h2>
      <p className="mt-1 text-slate-800">{title}</p>
      <p className="mt-2 text-xs text-slate-500">Generated by the Codexa mock agent from the prompt: ${JSON.stringify(prompt).slice(1, -1)}</p>
    </section>
  );
}
`;

const appFile = (prompt: string) => `import { useState } from "react";
import { Feature } from "./components/Feature";

const REQUEST = ${JSON.stringify(prompt)};

export default function App() {
  const [count, setCount] = useState(0);
  return (
    <main className="min-h-screen bg-slate-50 text-slate-900 flex items-center justify-center p-6">
      <div className="w-full max-w-md rounded-2xl bg-white p-8 shadow-sm border border-slate-200">
        <h1 className="text-2xl font-semibold tracking-tight">Codexa app</h1>
        <p className="mt-2 text-slate-600">This app was updated by the mock AI agent.</p>
        <Feature title={REQUEST} />
        <button
          onClick={() => setCount((c) => c + 1)}
          className="mt-6 inline-flex items-center rounded-lg bg-blue-600 px-4 py-2 text-sm font-medium text-white hover:bg-blue-700"
        >
          Clicked {count} {count === 1 ? "time" : "times"}
        </button>
      </div>
    </main>
  );
}
`;

async function* emitText(text: string): AsyncGenerator<ProviderEvent> {
  // Stream in small chunks so the UI's streaming path is exercised.
  for (let i = 0; i < text.length; i += 24) yield { type: "text_delta", text: text.slice(i, i + 24) };
}

function estimateTokens(request: ProviderRequest, output: string): { inputTokens: number; outputTokens: number } {
  const input = request.system.length + request.messages.reduce((n, m) => n + JSON.stringify(m).length, 0);
  return { inputTokens: Math.ceil(input / 4), outputTokens: Math.ceil(output.length / 4) };
}

export function createMockProvider(): AiProvider {
  return {
    id: "mock",
    async *stream(request: ProviderRequest): AsyncIterable<ProviderEvent> {
      const names = new Set(request.tools.map((t) => t.name));
      const prompt = extractUserRequest(request.messages);
      const made = priorToolCalls(request.messages);
      const madeNames = new Set(made.map((c) => c.name));
      const turn = request.messages.filter((m) => m.role === "assistant").length;
      const id = (i: number) => `mock_${turn}_${i}`;
      const finishWith = async function* (self: ProviderRequest, text: string, calls: ToolCall[], stop: "tool_use" | "end_turn") {
        yield* emitText(text);
        for (const c of calls) yield { type: "tool_call", ...c } as ProviderEvent;
        yield { type: "usage", ...estimateTokens(self, text + JSON.stringify(calls)) } as ProviderEvent;
        yield { type: "stop", reason: stop } as ProviderEvent;
      };

      if (request.abortSignal?.aborted) {
        yield { type: "stop", reason: "cancelled" };
        return;
      }

      // 1. Planning phase: only propose_plan is offered.
      if (names.has("propose_plan") && !madeNames.has("propose_plan")) {
        yield* finishWith(request, "I'll look at the project first, then make a focused change.", [
          { id: id(0), name: "propose_plan", input: { steps: ["Inspect the project files", "Read the main entry file", `Implement: ${prompt}`, "Run a typecheck if the sandbox is available", "Summarize the changes"] } },
        ], "tool_use");
        return;
      }

      const writeAllowed = names.has("write_file");
      const paths = listedPaths(request.messages);
      const lastUser = lastUserMessage(request.messages);
      const repairRequested = lastUser.includes("<validation_error>");

      // 2. Explore.
      if (names.has("list_files") && !madeNames.has("list_files")) {
        yield* finishWith(request, "Let me list the project files.", [{ id: id(0), name: "list_files", input: {} }], "tool_use");
        return;
      }
      if (names.has("read_file") && !madeNames.has("read_file")) {
        const target = paths.find((p) => p === "src/App.tsx") ?? paths.find((p) => p === "index.html") ?? paths.find((p) => p === "src/index.ts") ?? paths[0] ?? "README.md";
        yield* finishWith(request, `Reading ${target}.`, [{ id: id(0), name: "read_file", input: { path: target } }], "tool_use");
        return;
      }

      // 3. Ask mode: answer in text and stop.
      if (!writeAllowed) {
        const fileCount = paths.length;
        const answer = `Here is what I found about **${prompt}**:\n\n- The project has ${fileCount} file${fileCount === 1 ? "" : "s"}.\n- Entry points: ${paths.filter((p) => /^(src\/main\.tsx|src\/App\.tsx|index\.html|src\/index\.ts)$/.test(p)).join(", ") || "none detected"}.\n\n\`\`\`ts\n// Mock AI (development only) cannot reason about code; this answer is scripted.\n\`\`\``;
        yield* finishWith(request, answer, [], "end_turn");
        return;
      }

      // 4. Write a real change once.
      const wroteAlready = made.some((c) => c.name === "write_file" || c.name === "edit_file");
      if (!wroteAlready && !repairRequested) {
        if (paths.includes("src/App.tsx")) {
          yield* finishWith(request, "Adding a Feature component and wiring it into App.tsx.", [
            { id: id(0), name: "write_file", input: { path: "src/components/Feature.tsx", content: featureComponent(prompt) } },
            { id: id(1), name: "write_file", input: { path: "src/App.tsx", content: appFile(prompt) } },
          ], "tool_use");
          return;
        }
        if (paths.includes("index.html")) {
          yield* finishWith(request, "Adding a section to index.html.", [
            { id: id(0), name: "edit_file", input: { path: "index.html", search: "</body>", replace: `  <section data-codexa-feature>\n    <h2>Requested feature</h2>\n    <p>${escapeHtml(prompt)}</p>\n  </section>\n</body>` } },
          ], "tool_use");
          return;
        }
        yield* finishWith(request, "Documenting the requested change.", [
          { id: id(0), name: "write_file", input: { path: "FEATURE.md", content: `# Requested feature\n\n${prompt}\n\n_Written by the Codexa mock agent (development only)._\n` } },
        ], "tool_use");
        return;
      }

      // 5. Validate once if the sandbox offers it.
      if (names.has("run_command") && !madeNames.has("run_command") && !repairRequested) {
        yield* finishWith(request, "Running a typecheck.", [{ id: id(0), name: "run_command", input: { command: "typecheck" } }], "tool_use");
        return;
      }

      // 6. Done (also used for repair rounds: the mock cannot genuinely fix errors, so it says so).
      const summary = repairRequested
        ? `Validation reported errors that the mock agent cannot repair. The change for "${prompt}" was applied; please review the error output.`
        : `Implemented "${prompt}" with a small, real file change. The mock agent (development only) wrote a Feature component and updated the entry file.`;
      if (names.has("finish")) {
        yield* finishWith(request, "Wrapping up.", [
          { id: id(0), name: "finish", input: { summary, nextSteps: ["Review the changed files", "Run the app to see the change"], changedFilesSummary: "See the file change chips above." } },
        ], "tool_use");
        return;
      }
      yield* finishWith(request, summary, [], "end_turn");
    },
  };
}

function escapeHtml(s: string) {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}
