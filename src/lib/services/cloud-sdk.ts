/**
 * The Codexa Cloud client SDK that is written into a user's project when Cloud is turned on.
 * Pure string generation (no server-only imports) so it can be unit tested and shown in the panel.
 */

export type CloudSdkFile = { path: string; content: string; importHint: string };

/** Where the SDK lives in a project of this framework. Static sites get a plain ES module. */
export function cloudSdkPath(framework: string): string {
  return framework === "static" ? "codexa.js" : "src/lib/codexa.ts";
}

/** Short usage snippet for the Setup tab. */
export function cloudSdkSnippet(framework: string): string {
  if (framework === "static") {
    return `<script type="module">
  import { auth, db } from "./codexa.js";

  const user = await auth.user();
  const todos = await db.collection("todos").list({ where: { done: false } });
  await db.collection("todos").add({ title: "Ship it", done: false });
</script>`;
  }
  return `import { auth, db } from "./lib/codexa"; // from src/App.tsx

await auth.signUp({ email, password, name });
const user = await auth.user();
const todos = await db.collection("todos").list({ where: { done: false }, limit: 50 });
const todo = await db.collection("todos").add({ title: "Ship it", done: false });
await db.collection("todos").update(todo.id, { done: true });`;
}

export function cloudSdkFile(framework: string, apiBase: string, projectId: string): CloudSdkFile {
  const path = cloudSdkPath(framework);
  const base = JSON.stringify(apiBase);
  const key = JSON.stringify(`codexa:${projectId}:token`);
  if (framework === "static") {
    return { path, content: jsSdk(base, key), importHint: `import { auth, db } from "./codexa.js";` };
  }
  return { path, content: tsSdk(base, key), importHint: `import { auth, db } from "./lib/codexa";` };
}

const HEADER = `/**
 * Codexa Cloud client: the database and user accounts for this app.
 * Generated by Codexa when Cloud was turned on. No API keys are needed and none belong here:
 * access is controlled per collection in Codexa (Cloud → Data).
 *
 *   auth.signUp({ email, password, name }) · auth.signIn({ email, password }) · auth.signOut()
 *   auth.user() → the signed-in user or null · auth.onChange(cb) → unsubscribe
 *   db.collection("todos").list({ where, limit }) · .page({ where, limit, cursor }) · .get(id)
 *   .add(data) · .update(id, patch) · .remove(id)
 */`;

function tsSdk(base: string, key: string) {
  return `${HEADER}

const BASE_URL = ${base};
const TOKEN_KEY = ${key};

export type CloudUser = { id: string; email: string; name: string; createdAt: string };
export type CloudRecord<T> = T & { id: string; ownerId: string | null; createdAt: string; updatedAt: string };
export type Where = Record<string, string | number | boolean | null>;
export type ListOptions = { where?: Where; limit?: number; cursor?: string | null };
export type Page<T> = { items: CloudRecord<T>[]; nextCursor: string | null };

export class CloudError extends Error {
  code: string;
  status: number;
  constructor(status: number, code: string, message: string) {
    super(message);
    this.name = "CloudError";
    this.status = status;
    this.code = code;
  }
}

let memoryToken: string | null = null;
let currentUser: CloudUser | null | undefined;
let pendingUser: Promise<CloudUser | null> | null = null;
const listeners = new Set<(user: CloudUser | null) => void>();

function getToken(): string | null {
  try {
    return typeof localStorage === "undefined" ? memoryToken : localStorage.getItem(TOKEN_KEY);
  } catch {
    return memoryToken;
  }
}

function setSession(token: string | null, user: CloudUser | null) {
  memoryToken = token;
  try {
    if (typeof localStorage !== "undefined") {
      if (token) localStorage.setItem(TOKEN_KEY, token);
      else localStorage.removeItem(TOKEN_KEY);
    }
  } catch {
    // Storage unavailable (private mode): keep the session in memory.
  }
  currentUser = user;
  for (const cb of listeners) cb(user);
}

async function request<T>(method: string, path: string, body?: unknown): Promise<T> {
  const token = getToken();
  const headers: Record<string, string> = {};
  if (token) headers.Authorization = \`Bearer \${token}\`;
  if (body !== undefined) headers["Content-Type"] = "application/json";
  const res = await fetch(BASE_URL + path, { method, headers, body: body === undefined ? undefined : JSON.stringify(body) });
  const payload = (await res.json().catch(() => null)) as { data?: T; error?: { code?: string; message?: string } } | null;
  if (!res.ok) {
    if (res.status === 401 && token) setSession(null, null);
    throw new CloudError(res.status, payload?.error?.code ?? "error", payload?.error?.message ?? \`Request failed (\${res.status})\`);
  }
  return payload?.data as T;
}

type AuthResult = { user: CloudUser; token: string };

export const auth = {
  async signUp(input: { email: string; password: string; name?: string }): Promise<CloudUser> {
    const r = await request<AuthResult>("POST", "/auth/signup", input);
    setSession(r.token, r.user);
    return r.user;
  },
  async signIn(input: { email: string; password: string }): Promise<CloudUser> {
    const r = await request<AuthResult>("POST", "/auth/signin", input);
    setSession(r.token, r.user);
    return r.user;
  },
  async signOut(): Promise<void> {
    try {
      if (getToken()) await request("POST", "/auth/signout");
    } finally {
      setSession(null, null);
    }
  },
  /** The signed-in user, or null. Cached after the first call. */
  async user(): Promise<CloudUser | null> {
    if (!getToken()) return null;
    if (currentUser !== undefined) return currentUser;
    if (!pendingUser) {
      pendingUser = request<{ user: CloudUser | null }>("GET", "/auth/me")
        .then((r) => {
          if (!r.user) setSession(null, null);
          else currentUser = r.user;
          return r.user;
        })
        .finally(() => {
          pendingUser = null;
        });
    }
    return pendingUser;
  },
  /** Calls cb with the current user now and on every sign-in/sign-out. Returns an unsubscribe function. */
  onChange(cb: (user: CloudUser | null) => void): () => void {
    listeners.add(cb);
    auth.user().then((u) => listeners.has(cb) && cb(u), () => listeners.has(cb) && cb(null));
    return () => {
      listeners.delete(cb);
    };
  },
};

function query(opts: ListOptions): string {
  const q = new URLSearchParams();
  if (opts.where && Object.keys(opts.where).length) q.set("where", JSON.stringify(opts.where));
  if (opts.limit) q.set("limit", String(opts.limit));
  if (opts.cursor) q.set("cursor", opts.cursor);
  const s = q.toString();
  return s ? \`?\${s}\` : "";
}

export function collection<T extends object = Record<string, unknown>>(name: string) {
  const path = \`/collections/\${encodeURIComponent(name)}\`;
  return {
    /** Newest first. limit is 1–100 (default 50). */
    async list(opts: ListOptions = {}): Promise<CloudRecord<T>[]> {
      return (await request<Page<T>>("GET", path + query(opts))).items;
    },
    page(opts: ListOptions = {}): Promise<Page<T>> {
      return request<Page<T>>("GET", path + query(opts));
    },
    get(id: string): Promise<CloudRecord<T>> {
      return request<CloudRecord<T>>("GET", \`\${path}/\${encodeURIComponent(id)}\`);
    },
    add(data: T): Promise<CloudRecord<T>> {
      return request<CloudRecord<T>>("POST", path, data);
    },
    update(id: string, patch: Partial<T>): Promise<CloudRecord<T>> {
      return request<CloudRecord<T>>("PATCH", \`\${path}/\${encodeURIComponent(id)}\`, patch);
    },
    async remove(id: string): Promise<void> {
      await request("DELETE", \`\${path}/\${encodeURIComponent(id)}\`);
    },
  };
}

export const db = { collection };
`;
}

