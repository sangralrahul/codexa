/**
 * Bundles the template kits in templates-src/kits/<kit>/src (plus the shared files in
 * templates-src/kits/shared) into src/templates/kits/files.generated.ts, so the gallery templates
 * ship the kits' real source code. Run after editing a kit:
 *
 *   node scripts/build-template-kits.mjs
 *
 * Each kit is type-checked and built per template by scripts/capture-template-shots.ts.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const KITS = path.join(ROOT, "templates-src", "kits");
const OUT = path.join(ROOT, "src", "templates", "kits", "files.generated.ts");

function read(dir) {
  return Object.fromEntries(
    readdirSync(dir)
      .filter((f) => /\.(tsx?|css)$/.test(f))
      .sort()
      // Kits import shared files as "../../shared/X"; in a template they sit next to each other.
      .map((f) => [`src/${f}`, readFileSync(path.join(dir, f), "utf8").replaceAll("../../shared/", "./")]),
  );
}

const shared = read(path.join(KITS, "shared"));
const kits = ["site", "dashboard", "app"].map((k) => [k, { ...shared, ...read(path.join(KITS, k, "src")) }]);

const body = kits
  .map(([k, files]) => `  ${k}: {\n${Object.entries(files).map(([p, c]) => `    ${JSON.stringify(p)}: ${JSON.stringify(c)},`).join("\n")}\n  },`)
  .join("\n");

writeFileSync(
  OUT,
  `// Generated by scripts/build-template-kits.mjs from templates-src/kits. Do not edit by hand.\n\nexport const KIT_FILES: Record<"site" | "dashboard" | "app", Record<string, string>> = {\n${body}\n};\n`,
);
console.log(`wrote ${path.relative(ROOT, OUT)} (${kits.map(([k, f]) => `${k}: ${Object.keys(f).length} files`).join(", ")})`);

/*
 * Expo (React Native) templates: templates-src/expo/<template-id>/ holds each template's own source
 * (App.tsx and src/**). The shared project files (package.json, app.json, index.ts, metro.config.js,
 * tsconfig.json) are added in src/templates/expo/index.ts so every Expo template matches the runner's
 * prebuilt dependency set.
 */
const EXPO = path.join(ROOT, "templates-src", "expo");
const EXPO_OUT = path.join(ROOT, "src", "templates", "expo", "files.generated.ts");

function walk(dir, rel = "") {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const r = rel ? `${rel}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...walk(path.join(dir, entry.name), r));
    else if (/\.(tsx?|json)$/.test(entry.name)) out.push([r, readFileSync(path.join(dir, entry.name), "utf8")]);
  }
  return out;
}

const expoIds = readdirSync(EXPO, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();
const expoBody = expoIds
  .map((id) => `  ${JSON.stringify(id)}: {\n${walk(path.join(EXPO, id)).map(([p, c]) => `    ${JSON.stringify(p)}: ${JSON.stringify(c)},`).join("\n")}\n  },`)
  .join("\n");
writeFileSync(
  EXPO_OUT,
  `// Generated by scripts/build-template-kits.mjs from templates-src/expo. Do not edit by hand.\n\nexport const EXPO_TEMPLATE_FILES: Record<string, Record<string, string>> = {\n${expoBody}\n};\n`,
);
console.log(`wrote ${path.relative(ROOT, EXPO_OUT)} (${expoIds.join(", ")})`);
