#!/usr/bin/env node
/**
 * Extracts monochrome brand marks for the integrations Codexa users can connect
 * (the providers registry in src/lib/integrations/providers, plus GitHub) from the
 * CC0 `simple-icons` package into src/components/brand/marks.generated.ts.
 * Zero runtime dependency: only the SVG path data is copied.
 *
 *   node scripts/extract-brand-marks.mjs
 *
 * A brand missing from simple-icons is written as null and rendered as a monogram
 * tile by <BrandMark>. Never hand-draw a logo.
 */
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const require = createRequire(import.meta.url);
const si = require("simple-icons");
// The package's "exports" hides package.json, so read it from disk next to the resolved entry.
const pkgDir = path.dirname(require.resolve("simple-icons")).replace(/(node_modules[\\/]simple-icons).*$/, "$1");
const { version } = JSON.parse(readFileSync(path.join(pkgDir, "package.json"), "utf8"));

// Codexa id → simple-icons export. Customer.io and Cloudflare are Codexa's own infrastructure,
// not user integrations, so they are deliberately absent.
const BRANDS = [
  ["openai", "siOpenai", "OpenAI"],
  ["anthropic", "siAnthropic", "Anthropic"],
  ["stripe", "siStripe", "Stripe"],
  ["razorpay", "siRazorpay", "Razorpay"],
  ["resend", "siResend", "Resend"],
  ["vercel", "siVercel", "Vercel"],
  ["postgres", "siPostgresql", "PostgreSQL"],
  ["supabase", "siSupabase", "Supabase"],
  ["github", "siGithub", "GitHub"],
];

const rows = BRANDS.map(([id, key, fallbackTitle]) => {
  const icon = si[key];
  return { id, title: icon?.title ?? fallbackTitle, path: icon?.path ?? null };
});

const out = `// Generated by scripts/extract-brand-marks.mjs — do not edit by hand.
// Source: simple-icons@${version} (CC0 1.0 Universal, https://simpleicons.org).
// Marks are shown for nominative use only: trademarks belong to their owners; no partnership implied.
// A null path means the mark is not in simple-icons; <BrandMark> renders a monogram tile instead.

export const SIMPLE_ICONS_VERSION = ${JSON.stringify(version)};

export const BRAND_IDS = ${JSON.stringify(rows.map((r) => r.id))} as const;

export type BrandId = (typeof BRAND_IDS)[number];

export const BRAND_MARKS: Record<BrandId, { title: string; path: string | null }> = {
${rows.map((r) => `  ${JSON.stringify(r.id)}: { title: ${JSON.stringify(r.title)}, path: ${r.path ? JSON.stringify(r.path) : "null"} },`).join("\n")}
};
`;

const target = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "components", "brand", "marks.generated.ts");
writeFileSync(target, out);
const missing = rows.filter((r) => !r.path).map((r) => r.id);
console.log(`Wrote ${path.relative(process.cwd(), target)} (${rows.length - missing.length} marks${missing.length ? `; monogram fallback: ${missing.join(", ")}` : ""}).`);
