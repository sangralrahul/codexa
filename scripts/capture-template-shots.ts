/**
 * Captures real screenshots of every starter template's own build and writes the Express
 * templates' real route lists.
 *
 *   npx tsx scripts/capture-template-shots.ts              # every template
 *   npx tsx scripts/capture-template-shots.ts --only vite-react-crm,static-blog
 *   npx tsx scripts/capture-template-shots.ts --routes-only  # just api-routes.generated.ts
 *   npx tsx scripts/capture-template-shots.ts --only vite-react-crm --dry /tmp/look  # PNGs to a folder; public/ and shots.ts untouched
 *
 * For each Vite or static template it writes the files to a temp directory, type-checks and builds
 * Vite templates with the runner's prebuilt dependency set (no install), serves the output over a
 * tiny local HTTP server, and captures a 1440×900 viewport at 2× with the preinstalled Playwright
 * Chromium (never `playwright install`). Outputs in public/templates/:
 *   <id>@2x.webp  2880w (quality 78)   <id>.webp  1440w   <id>-720.webp  720w
 * then rewrites the data block in src/components/templates/shots.ts. When a capture fails the old
 * <id>.webp is kept and marked `retina: false`, so srcset never points at a missing file.
 *
 * Env: CAPTURE_TMP (work dir, default os.tmpdir()), CODEXA_BASE_DIR (prebuilt deps; default
 * /var/codexa/base), PLAYWRIGHT_BROWSERS_PATH (where Chromium is installed).
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, statSync, symlinkSync, writeFileSync } from "node:fs";
import { createServer, type Server } from "node:http";
import { tmpdir } from "node:os";
import path from "node:path";
import sharp from "sharp";
import { chromium, type Browser } from "playwright";
import { TEMPLATES, type Template } from "../src/templates";
import { parseExpressRoutes } from "../src/components/templates/route-parse";

const ROOT = process.cwd();
const PUBLIC_DIR = path.join(ROOT, "public", "templates");
const SHOTS_FILE = path.join(ROOT, "src", "components", "templates", "shots.ts");
const ROUTES_FILE = path.join(ROOT, "src", "components", "templates", "api-routes.generated.ts");
const WORK = path.join(process.env.CAPTURE_TMP ?? tmpdir(), "codexa-template-shots");
const BASE = process.env.CODEXA_BASE_DIR ?? "/var/codexa/base";
const VIEWPORT = { width: 1440, height: 900 };

const args = process.argv.slice(2);
const only = (() => {
  const i = args.indexOf("--only");
  return i >= 0 ? new Set(args[i + 1]?.split(",").map((s) => s.trim())) : null;
})();
const routesOnly = args.includes("--routes-only");
const dryDir = (() => {
  const i = args.indexOf("--dry");
  return i >= 0 ? path.resolve(args[i + 1] ?? ".") : null;
})();

type ShotEntry = { retina: boolean; small: boolean; phone?: boolean };
const PHONE = { width: 390, height: 844 };

function log(msg: string) {
  console.log(`[shots] ${msg}`);
}

/* ---------------------------------------------------------------- routes */

function writeRoutes() {
  const express = TEMPLATES.filter((t) => t.framework === "node-express");
  const lines = express.map((t) => {
    const routes = parseExpressRoutes(t.files);
    const rows = routes.map((r) => `    { method: "${r.method}", path: "${r.path}" },`).join("\n");
    return `  "${t.id}": [\n${rows}\n  ],`;
  });
  const out = `// Generated by scripts/capture-template-shots.ts from each Express template's own source files.
// Do not edit by hand: re-run \`npx tsx scripts/capture-template-shots.ts --routes-only\`.
import type { ApiRoute } from "./route-parse";

export const TEMPLATE_API_ROUTES: Record<string, ApiRoute[]> = {
${lines.join("\n")}
};
`;
  writeFileSync(ROUTES_FILE, out);
  log(`routes: ${express.map((t) => `${t.id} (${parseExpressRoutes(t.files).length})`).join(", ")}`);
}

/* ---------------------------------------------------------------- build */

function run(cmd: string, argv: string[], cwd: string) {
  const r = spawnSync(cmd, argv, { cwd, encoding: "utf8", env: { ...process.env, NODE_ENV: "production" } });
  if (r.status !== 0) throw new Error(`${path.basename(argv[0] ?? cmd)} failed:\n${(r.stdout ?? "") + (r.stderr ?? "")}`.slice(0, 4000));
}

/** Writes the template, builds it if needed, and returns the directory to serve. */
function prepare(t: Template): string {
  const dir = path.join(WORK, t.id);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  for (const [file, content] of Object.entries(t.files)) {
    const p = path.join(dir, file);
    mkdirSync(path.dirname(p), { recursive: true });
    writeFileSync(p, content);
  }
  if (t.framework === "static") return dir;
  const modules = path.join(BASE, t.framework, "node_modules");
  if (!existsSync(modules)) throw new Error(`prebuilt dependencies not found at ${modules} (set CODEXA_BASE_DIR)`);
  symlinkSync(modules, path.join(dir, "node_modules"), "dir");
  // Same as the template's `npm run build` (tsc -b && vite build), without writing tsbuildinfo.
  run(process.execPath, [path.join(modules, "typescript", "bin", "tsc"), "-p", "tsconfig.json", "--noEmit"], dir);
  run(process.execPath, [path.join(modules, "vite", "bin", "vite.js"), "build", "--logLevel", "error", "--emptyOutDir"], dir);
  return path.join(dir, "dist");
}

const TYPES: Record<string, string> = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript",
  ".mjs": "text/javascript",
  ".css": "text/css",
  ".json": "application/json",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".webp": "image/webp",
  ".ico": "image/x-icon",
  ".woff2": "font/woff2",
};

/** Static file server with an index.html fallback (SPA routes and directory indexes). */
function serve(root: string): Promise<{ server: Server; url: string }> {
  const server = createServer((req, res) => {
    const pathname = decodeURIComponent(new URL(req.url ?? "/", "http://x").pathname);
    let file = path.join(root, path.normalize(pathname).replace(/^(\.\.[/\\])+/, ""));
    if (!file.startsWith(root)) file = path.join(root, "index.html");
    if (existsSync(file) && statSync(file).isDirectory()) file = path.join(file, "index.html");
    if (!existsSync(file)) file = path.join(root, "index.html");
    res.writeHead(200, { "content-type": TYPES[path.extname(file)] ?? "application/octet-stream", "cache-control": "no-store" });
    res.end(readFileSync(file));
  });
  return new Promise((resolve) => server.listen(0, "127.0.0.1", () => resolve({ server, url: `http://127.0.0.1:${(server.address() as { port: number }).port}` })));
}

/* ---------------------------------------------------------------- capture */

async function capture(browser: Browser, t: Template): Promise<ShotEntry> {
  const root = prepare(t);
  const { server, url } = await serve(root);
  try {
    const context = await browser.newContext({ viewport: VIEWPORT, deviceScaleFactor: 2, colorScheme: "light", reducedMotion: "reduce", locale: "en-US", timezoneId: "UTC" });
    const page = await context.newPage();
    const errors: string[] = [];
    page.on("pageerror", (e) => errors.push(e.message));
    await page.goto(url + (t.previewPath ?? "/"), { waitUntil: "networkidle" });
    await page.evaluate(() => document.fonts.ready);
    await page.waitForTimeout(500);
    if (errors.length) throw new Error(`page errors: ${errors.join(" | ")}`);
    const png = await page.screenshot({ type: "png" });
    await context.close();
    if (dryDir) {
      await sharp(png).resize({ width: 1440 }).png().toFile(path.join(dryDir, `${t.id}.png`));
      if (t.category === "mobile-first") {
        const mobile = await browser.newContext({ viewport: PHONE, deviceScaleFactor: 2, isMobile: true, hasTouch: true, colorScheme: "light", reducedMotion: "reduce" });
        const mp = await mobile.newPage();
        await mp.goto(url + (t.previewPath ?? "/"), { waitUntil: "networkidle" });
        await mp.waitForTimeout(300);
        await sharp(await mp.screenshot({ type: "png" })).png().toFile(path.join(dryDir, `${t.id}-phone.png`));
        await mobile.close();
      }
      return { retina: true, small: true };
    }
    await sharp(png).webp({ quality: 78, effort: 6 }).toFile(path.join(PUBLIC_DIR, `${t.id}@2x.webp`));
    await sharp(png).resize({ width: 1440 }).webp({ quality: 80, effort: 6 }).toFile(path.join(PUBLIC_DIR, `${t.id}.webp`));
    await sharp(png).resize({ width: 720 }).webp({ quality: 80, effort: 6 }).toFile(path.join(PUBLIC_DIR, `${t.id}-720.webp`));
    // Mobile-first starters also get a real phone-viewport capture (shown in a phone frame).
    let phone = false;
    if (t.category === "mobile-first") {
      const mobile = await browser.newContext({ viewport: PHONE, deviceScaleFactor: 2, isMobile: true, hasTouch: true, colorScheme: "light", reducedMotion: "reduce", locale: "en-US", timezoneId: "UTC" });
      const mp = await mobile.newPage();
      await mp.goto(url + (t.previewPath ?? "/"), { waitUntil: "networkidle" });
      await mp.evaluate(() => document.fonts.ready);
      await mp.waitForTimeout(400);
      await sharp(await mp.screenshot({ type: "png" })).webp({ quality: 80, effort: 6 }).toFile(path.join(PUBLIC_DIR, `${t.id}-phone.webp`));
      await mobile.close();
      phone = true;
    }
    return phone ? { retina: true, small: true, phone: true } : { retina: true, small: true };
  } finally {
    server.close();
  }
}

function readCurrentShots(): Map<string, ShotEntry> {
  const src = readFileSync(SHOTS_FILE, "utf8");
  const map = new Map<string, ShotEntry>();
  for (const m of src.matchAll(/\["([a-z0-9-]+)", \{ retina: (true|false), small: (true|false)(?:, phone: (true|false))? \}\]/g))
    map.set(m[1], m[4] === "true" ? { retina: m[2] === "true", small: m[3] === "true", phone: true } : { retina: m[2] === "true", small: m[3] === "true" });
  return map;
}

function writeShots(map: Map<string, ShotEntry>) {
  const src = readFileSync(SHOTS_FILE, "utf8");
  const rows = [...map.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([id, s]) => `  ["${id}", { retina: ${s.retina}, small: ${s.small}${s.phone ? ", phone: true" : ""} }],`)
    .join("\n");
  const block = `// <capture-data> (generated by scripts/capture-template-shots.ts; edit by re-running the script)\nconst DATA: [string, TemplateShot][] = [\n${rows}\n];\n// </capture-data>`;
  const next = src.replace(/\/\/ <capture-data>[\s\S]*?\/\/ <\/capture-data>/, block);
  if (next === src && !src.includes(block)) throw new Error("capture-data markers not found in shots.ts");
  writeFileSync(SHOTS_FILE, next);
}

async function main() {
  if (!dryDir) writeRoutes();
  if (routesOnly) return;
  if (dryDir) mkdirSync(dryDir, { recursive: true });
  mkdirSync(PUBLIC_DIR, { recursive: true });
  mkdirSync(WORK, { recursive: true });
  const shots = readCurrentShots();
  const targets = TEMPLATES.filter((t) => t.framework === "vite-react" || t.framework === "static").filter((t) => !only || only.has(t.id));
  const browser = await chromium.launch();
  const failed: string[] = [];
  try {
    for (const t of targets) {
      const started = Date.now();
      try {
        shots.set(t.id, await capture(browser, t));
        log(`${t.id}: captured in ${((Date.now() - started) / 1000).toFixed(1)}s`);
      } catch (err) {
        failed.push(t.id);
        const old = existsSync(path.join(PUBLIC_DIR, `${t.id}.webp`));
        if (old) shots.set(t.id, { retina: false, small: false });
        else shots.delete(t.id);
        log(`${t.id}: FAILED, ${old ? "keeping the old shot (retina: false)" : "no shot"}\n${err instanceof Error ? err.message : String(err)}`);
      }
    }
  } finally {
    await browser.close();
  }
  if (!dryDir) writeShots(shots);
  log(`${targets.length - failed.length}/${targets.length} captured${failed.length ? `; failed: ${failed.join(", ")}` : ""}`);
  if (failed.length) process.exitCode = 1;
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
