/**
 * Codexa's Cloudflare Worker entry. Wraps the Next.js app built by OpenNext
 * and adds what the app needs from the edge:
 *   <token>.<PREVIEW_HOST>  → the project's container (live preview, hot reload)
 *   <slug>.<DEPLOY_HOST>    → Codexa-hosted sites from R2
 *   <verified custom domain> → the same site (needs Cloudflare for SaaS custom hostnames)
 *   /realtime?token=…       → the project's presence room (WebSocket)
 *   cron                    → background jobs (POST /api/internal/cron)
 * Everything else is the Next.js app.
 */
