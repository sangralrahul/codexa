const previewCache = new Map<string, { projectId: string | null; at: number }>();

async function projectForPreview(env: Env, token: string): Promise<string | null> {
  const hit = previewCache.get(token);
  if (hit && Date.now() - hit.at < 10_000) return hit.projectId;
  const row = await env.DB.prepare("SELECT project_id FROM runtime_sessions WHERE preview_token = ?1 AND status IN ('starting', 'running') ORDER BY started_at DESC LIMIT 1")
    .bind(token)
    .first<{ project_id: string }>();
  const projectId = row?.project_id ?? null;
  previewCache.set(token, { projectId, at: Date.now() });
  return projectId;
}

async function connectPresence(request: Request, env: Env): Promise<Response> {
  if (request.headers.get("upgrade")?.toLowerCase() !== "websocket") return new Response("Expected a WebSocket", { status: 426 });
  const token = new URL(request.url).searchParams.get("token") ?? "";
  const dot = token.lastIndexOf(".");
  if (dot <= 0 || !env.SESSION_SECRET) return new Response("invalid or expired token", { status: 401 });
  const encoded = token.slice(0, dot);
  const expected = await hmac(env.SESSION_SECRET, encoded);
  if (!timingSafeEqualStr(expected, token.slice(dot + 1))) return new Response("invalid or expired token", { status: 401 });
  let payload: { projectId?: string; userId?: string; name?: string; color?: string; exp?: number };
  try {
    payload = JSON.parse(atob(encoded.replace(/-/g, "+").replace(/_/g, "/")));
  } catch {
    return new Response("invalid or expired token", { status: 401 });
  }
  if (!payload.projectId || !payload.userId || typeof payload.exp !== "number" || payload.exp <= Date.now()) return new Response("invalid or expired token", { status: 401 });
  const stub = env.PRESENCE.get(env.PRESENCE.idFromName(payload.projectId));
  const headers = new Headers(request.headers);
  headers.set("x-codexa-peer", JSON.stringify({ userId: payload.userId, name: payload.name, color: payload.color }));
  return stub.fetch(new Request(request.url, { headers }) as never) as unknown as Response;
}

/** The app's own host name from APP_URL (codexa.example.com), or null when it is not set. */
function appHostOf(env: Env): string | null {
  try {
    return env.APP_URL ? new URL(env.APP_URL).hostname.toLowerCase() : null;
  } catch {
    return null;
  }
}

/** The registrable zone Codexa runs under (from DEPLOY_HOST, e.g. -sites.example.com → example.com). */
function ownZone(env: Env): string | null {
  const base = hostOnly(env.DEPLOY_HOST ?? "");
  return base ? base.replace(/^-/, "").split(".").slice(-2).join(".") : null;
}

const worker = {
  async fetch(request: Request, env: Env, ctx: ExecutionContext): Promise<Response> {
    const url = new URL(request.url);
    const host = url.hostname.toLowerCase();

    // www.<app host> → <app host>, permanently, keeping the path and query.
    const appHost = appHostOf(env);
    if (appHost && host === `www.${appHost}`) return Response.redirect(`https://${appHost}${url.pathname}${url.search}`, 301);

    const previewToken = labelUnder(host, hostOnly(env.PREVIEW_HOST));
    if (previewToken) {
      // Never let a preview request crash the Worker: Cloudflare's error page can't be shown inside the editor.
      try {
        const projectId = await projectForPreview(env, previewToken);
        if (!projectId) return previewProblem(404, "This preview is not running", "Start it again with Run in the Codexa workspace.");
        return (await env.SANDBOX.get(env.SANDBOX.idFromName(projectId)).fetch(request as never)) as unknown as Response;
      } catch (err) {
        const message = err instanceof Error ? err.message : String(err);
        console.error(`[preview] ${previewToken}: ${message}`);
        return previewProblem(502, "The preview couldn't be reached", `${message}. Reload in a few seconds, or press Stop and Run again in the workspace.`);
      }
    }

    const siteSlug = labelUnder(host, hostOnly(env.DEPLOY_HOST));
    if (siteSlug) return serveSite(request, env, { slug: siteSlug }, ctx);

    // A host outside Codexa's own zone can only be a customer's custom domain.
    const zone = ownZone(env);
    if (zone && host !== zone && !host.endsWith(`.${zone}`) && host !== "localhost" && (await isCustomDomain(env, host))) return serveSite(request, env, { domain: host }, ctx);

    if (url.pathname === "/realtime") return connectPresence(request, env);

    return openNext.fetch(request, env, ctx);
  },

  async scheduled(_event: ScheduledEvent, env: Env, ctx: ExecutionContext) {
    if (!env.SESSION_SECRET) return;
    const signature = await hmac(env.SESSION_SECRET, "codexa-cron");
    const request = new Request("https://codexa.internal/api/internal/cron", { method: "POST", headers: { "x-codexa-cron": signature } });
    ctx.waitUntil(openNext.fetch(request, env, ctx).then((r) => r.text()));
  },
};

export default worker;
